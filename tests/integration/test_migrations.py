"""Migrations against real Postgres: they build the schema, reverse cleanly, match the models."""

import pytest
from sqlalchemy import Engine, inspect

from tests.integration.conftest import alembic_check, alembic_downgrade, alembic_upgrade

pytestmark = pytest.mark.integration

SPEC_TABLES = {"accounts", "deposits", "bets", "alerts", "cases", "alert_labels"}


def _tables(engine: Engine) -> set[str]:
    # alembic_version is Alembic's own bookkeeping table, not part of our schema.
    return set(inspect(engine).get_table_names()) - {"alembic_version"}


def test_upgrade_head_on_empty_db_creates_the_six_tables(empty_db: Engine) -> None:
    assert _tables(empty_db) == set()

    alembic_upgrade(empty_db)

    assert _tables(empty_db) == SPEC_TABLES


def test_upgrade_downgrade_upgrade_is_reversible(empty_db: Engine) -> None:
    alembic_upgrade(empty_db)
    alembic_downgrade(empty_db, "base")

    assert _tables(empty_db) == set()

    alembic_upgrade(empty_db)

    assert _tables(empty_db) == SPEC_TABLES


def test_models_and_migrations_are_in_sync(empty_db: Engine) -> None:
    alembic_upgrade(empty_db)

    # Raises AutogenerateDiffsDetected (listing the differences) if they drift.
    alembic_check(empty_db)
