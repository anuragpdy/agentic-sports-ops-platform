"""Fixtures for tests that need a real Postgres (the `sportsops_test` database).

Where the URL comes from: TEST_DATABASE_URL (environment or .env). It is read here rather
than in app Settings because only the tests need it. Whether the tests run, skip or fail is
decided by tests/integration/db_guard.py (unit-tested on its own).
"""

from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from pydantic import SecretStr
from pydantic_settings import BaseSettings, SettingsConfigDict
from sqlalchemy import Connection, Engine, create_engine, pool, text

from tests.integration.db_guard import decide

ALEMBIC_INI = Path(__file__).resolve().parents[2] / "alembic.ini"


class _TestDbSettings(BaseSettings):
    model_config = SettingsConfigDict(env_file=".env", env_file_encoding="utf-8", extra="ignore")

    test_database_url: SecretStr | None = None
    app_env: str = "local"


@pytest.fixture(scope="session")
def engine() -> Iterator[Engine]:
    settings = _TestDbSettings()
    raw = settings.test_database_url
    decision = decide(raw.get_secret_value() if raw else None, settings.app_env)
    if decision.action == "skip":
        pytest.skip(decision.reason)
    if decision.action == "fail" or decision.url is None:
        pytest.fail(decision.reason)

    # NullPool: no connections stay open between tests, so DROP SCHEMA never waits on one.
    eng = create_engine(decision.url, poolclass=pool.NullPool)
    yield eng
    eng.dispose()


def alembic_upgrade(engine: Engine, revision: str = "head") -> None:
    """Run `alembic upgrade` on the test DB, through the same migrations/env.py as the CLI."""
    with engine.begin() as conn:
        cfg = Config(ALEMBIC_INI)
        cfg.attributes["connection"] = conn
        command.upgrade(cfg, revision)


def alembic_downgrade(engine: Engine, revision: str = "base") -> None:
    with engine.begin() as conn:
        cfg = Config(ALEMBIC_INI)
        cfg.attributes["connection"] = conn
        command.downgrade(cfg, revision)


def alembic_check(engine: Engine) -> None:
    """`alembic check`: raises AutogenerateDiffsDetected if models and migrations differ."""
    with engine.connect() as conn:
        cfg = Config(ALEMBIC_INI)
        cfg.attributes["connection"] = conn
        command.check(cfg)


@pytest.fixture(scope="module")
def migrated_db(engine: Engine) -> Engine:
    """A test DB at `head`, built once per test module (migrating is the slow part)."""
    with engine.begin() as conn:
        conn.execute(text("DROP SCHEMA public CASCADE"))
        conn.execute(text("CREATE SCHEMA public"))
    alembic_upgrade(engine)
    return engine


@pytest.fixture
def db(migrated_db: Engine) -> Iterator[Connection]:
    """A connection inside a transaction that is always rolled back.

    Each test starts from empty tables and leaves nothing behind, with no cleanup code.
    """
    with migrated_db.connect() as conn:
        trans = conn.begin()
        try:
            yield conn
        finally:
            trans.rollback()


@pytest.fixture
def empty_db(engine: Engine) -> Engine:
    """A test DB with nothing in it, even if an earlier test failed halfway through a migration.

    Dropping the schema is more robust than `downgrade base`, which needs a known state.
    """
    with engine.begin() as conn:
        conn.execute(text("DROP SCHEMA public CASCADE"))
        conn.execute(text("CREATE SCHEMA public"))
    return engine
